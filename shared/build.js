#!/usr/bin/env node
/* Builds shared/reminder/reminder.iife.js from reminder.js, and writes plane/icon art.
 * Usage:  node shared/build.js            (IIFE + SVGs)
 *         node shared/build.js --png      (also renders icon PNGs; needs `sharp`, auto-found in ~/.aside/cn-tools or node_modules)
 */
'use strict';
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const src = fs.readFileSync(path.join(dir, 'reminder/reminder.js'), 'utf8');

/* ---- IIFE ---- */
const names = [];
let body = src
  .replace(/^export default [^;]*;\s*$/m, '')
  .replace(/^export (function|const|var|let) ([A-Za-z_$][\w$]*)/gm, (m, kind, name) => { names.push(name); return kind + ' ' + name; });
const api = names.filter((n) => !/^PLANE_/.test(n)).concat(['PLANE_VIEWBOX', 'PLANE_INNER']);
const iife =
  '/* MeetingPlz reminder (generated by shared/build.js from reminder.js; do not edit). Global: MeetingPlzReminder */\n' +
  '(function (root) {\n"use strict";\n' + body + '\nroot.MeetingPlzReminder = { ' + api.map((n) => n + ': ' + n).join(', ') + ' };\n' +
  '})(typeof self !== "undefined" ? self : this);\n';
fs.writeFileSync(path.join(dir, 'reminder/reminder.iife.js'), iife);

/* ---- art ---- */
const PLANE_VIEWBOX = /PLANE_VIEWBOX = '([^']+)'/.exec(src)[1];
const planeInner = eval(src.match(/export const PLANE_INNER =([\s\S]*?);\n/)[1]);
const attrs = 'fill="none" stroke="#111" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
fs.mkdirSync(path.join(dir, 'art'), { recursive: true });
fs.writeFileSync(path.join(dir, 'art/plane.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${PLANE_VIEWBOX}" ${attrs}>${planeInner}</svg>\n`);

// App icon: plane (viewBox 240x100) centred on a 1024 square, tilted up a little.
function icon({ paper, stroke, detail = true, tilt = -9, scale = 3.5, bg = 'ink', size = 1024 }) {
  const ink = '#111111', pap = '#FFFFFF';
  const line = bg === 'ink' ? pap : ink;
  const fill = bg === 'ink' ? ink : pap;
  const bgFill = bg === 'ink' ? ink : pap;
  const inner = planeInner
    .replace(/fill="#fff"/g, `fill="${fill}"`)
    .replace(/<path d="M58 53[^>]*\/>/, detail ? (m) => m.replace('stroke-width="5"', 'stroke-width="' + (stroke * 2.6) + '"') : '')
    .replace(/<path d="M184 43[^>]*\/>/, detail ? (m) => m : '');
  const sw = stroke;
  const tx = 512 - 120 * scale, ty = 512 - 52 * scale;
  const border = bg === 'ink' ? '' : `<rect x="12" y="12" width="1000" height="1000" rx="228" fill="none" stroke="${ink}" stroke-width="${Math.max(10, stroke * scale)}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 1024 1024">\n` +
    `<rect width="1024" height="1024" rx="232" fill="${bgFill}"/>${border}\n` +
    `<g transform="rotate(${tilt} 512 512) translate(${tx} ${ty}) scale(${scale})" fill="none" stroke="${line}" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round">${inner}</g>\n</svg>\n`;
}

const variants = {
  1024: { stroke: 4.2 }, 512: { stroke: 4.4 }, 192: { stroke: 5.4 }, 180: { stroke: 5.6 }, 32: { stroke: 9, detail: false, scale: 3.6 }
};
fs.writeFileSync(path.join(dir, 'art/icon.svg'), icon({ stroke: 4.2 }));
fs.writeFileSync(path.join(dir, 'art/icon-paper.svg'), icon({ stroke: 4.2, bg: 'paper' }));

function findSharp() {
  const cands = ['sharp', path.join(process.env.HOME || '', '.aside/cn-tools/node_modules/sharp')];
  for (const c of cands) { try { return require(c); } catch (e) {} }
  return null;
}

(async () => {
  if (process.argv.includes('--png')) {
    const sharp = findSharp();
    if (!sharp) { console.error('sharp not found; skipping PNG render'); return; }
    for (const [size, v] of Object.entries(variants)) {
      const svg = icon(Object.assign({ size: +size }, v));
      await sharp(Buffer.from(svg), { density: 72 * (+size / 1024) < 72 ? 300 : 72 }).resize(+size, +size).png().toFile(path.join(dir, `art/icon-${size}.png`));
    }
    await sharp(Buffer.from(icon({ stroke: 4.2, bg: 'paper' }))).resize(1024, 1024).png().toFile(path.join(dir, 'art/icon-paper-1024.png'));
  }
  console.log('built reminder.iife.js (' + iife.length + ' bytes), art svgs' + (process.argv.includes('--png') ? ', pngs' : ''));
})();
